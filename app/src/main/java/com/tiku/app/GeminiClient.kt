/**
 * ROUND 37 — TIKA, the in-chat AI (owner's order, Meta-AI style).
 *
 * The chat composer understands two commands (see RdChatContent):
 *   /tiku <question>  -> a TEXT answer from Gemini
 *   /tika <prompt>    -> an IMAGE generated by Gemini
 * The asking client makes the call and then posts the result into the
 * thread as a normal encrypted message carrying the additive `ai`
 * flag (TikuMessage.ai) — both phones render it as Tika's bubble.
 *
 * Transport is deliberately dependency-free: HttpURLConnection +
 * org.json (both already used across this codebase), the key riding
 * the `x-goog-api-key` header from GeminiConfig. Every model in the
 * config's cascade is tried in order — a 429 / 503 / 404 / empty
 * answer falls through to the next model, so one model's quota or a
 * renamed model never silences Tika while another still answers.
 * Outcomes are honest: [Outcome.Quota] only when the cascade saw a
 * 429 and nothing succeeded, [Outcome.Failed] for everything else —
 * the caller toasts and posts NOTHING fake.
 *
 * Images carry one extra safety net (ROUND 38): when every Gemini
 * image model has failed — the owner's key currently has zero image
 * quota — [generateImage] falls back to Pollinations.ai, a free
 * no-key image service, and a hit there returns through the exact
 * same success path. Gemini stays FIRST: the day its image quota
 * opens, it silently takes over again and the fallback never runs.
 *
 * Timeouts are generous (image generation is slow): 20 s connect,
 * 60 s read per Gemini model, 120 s read for the fallback (its
 * queue can crawl), all on Dispatchers.IO.
 *
 * ROUND 41 adds three things: a `/babeg` game writer ([generateGame]
 * — Gemini cascade, then MiniMax via NVIDIA, one strict validator so
 * only a complete HTML game is ever posted); a Cloudflare FLUX image
 * step between the Gemini image cascade and Pollinations (skipped
 * while its config is blank); and 180 s reads on game calls.
 *
 * ROUND 43 adds [answerImage]: a /tiku question about ONE photo the
 * user explicitly replied to (vision). The image reaches Gemini only
 * through that deliberate attach — never from chat history.
 *
 * ROUND 51 (games that "loaded forever"): the game output budget went
 * 8192 -> 32768 tokens on BOTH writers (thinking-era models were
 * truncating the document before </html>, and MiniMax — a reasoning
 * model — was returning content=null at 8000 max_tokens after
 * spending the whole budget on reasoning), game extraction now skips
 * `thought` parts, and the whole cascade carries a 10-minute hard
 * ceiling so the "creating" indicator can never spin unbounded.
 */
object GeminiClient {

    sealed interface Outcome<out T> {
        data class Ok<T>(val value: T) : Outcome<T>
        data object Quota : Outcome<Nothing>
        data object Failed : Outcome<Nothing>
    }

    private sealed interface Raw {
        data class Ok(val json: JSONObject) : Raw
        data object Quota : Raw
        data object Failed : Raw
    }

