    /** A /tiku text answer: cascade TEXT_MODELS until one returns a
     *  non-empty answer. */
    suspend fun answerText(prompt: String): Outcome<String> {
        if (isMakerQuestion(prompt)) return Outcome.Ok(MAKER_ANSWER)
        if (Config.PREVIEW_UI_ONLY) {
            return Outcome.Ok(
                "Preview mode — in the real app, Tika's Gemini answer appears here. You asked: $prompt",
            )
        }
        val body = JSONObject().apply {
            put("system_instruction", JSONObject().apply {
                put("parts", JSONArray().put(JSONObject().put("text", IDENTITY)))
            })
            put("contents", JSONArray().put(JSONObject().apply {
                put("parts", JSONArray().put(JSONObject().put("text", prompt)))
            }))
        }
        val (outcome, sawBlock) = cascadeTextAnswer(body)
        return maybeWzFallback(
            outcome = outcome,
            sawBlock = sawBlock,
            systemText = IDENTITY + "\n\n" + WZ_ROUTE_GUARD,
            userText = prompt,
        )
    }

    /** ROUND 68 (WS4): the COMPANION's own cascade — the same three
     *  text models, but fastest first. gemini-3.1-flash-lite is the
     *  lightest tier (verified answering live 2026-11-05, see
     *  GeminiConfig), so a companion reply tries it before the
     *  heavier 3.5-flash; 3.8-flash stays last as the capacity
     *  fallback. The /tiku path ([answerText]) keeps TEXT_MODELS
     *  order untouched — only the companion moves. One POST per
     *  reply either way: no extra round-trips were added anywhere
     *  (the persona + full history ride in the single
     *  generateContent body, as before). Streaming was NOT added:
     *  this client is built on the non-streaming generateContent
     *  endpoint and the local store appends whole messages — a
     *  streamGenerateContent path would need incremental UI +
     *  persist-on-complete, a separate change (see worker A
     *  report). */
    private val COMPANION_TEXT_MODELS = listOf(
        "gemini-3.1-flash-lite",
        "gemini-3.5-flash",
        "gemini-3.8-flash",
    )

    /** The companion cascade — [cascadeTextAnswer]'s exact logic
     *  over [COMPANION_TEXT_MODELS]. ROUND 70: also reports whether
     *  any model answered empty (the blocked/empty signal) so the
     *  public entry point can decide on the fallback provider. */
    private suspend fun cascadeCompanionAnswer(body: JSONObject): Pair<Outcome<String>, Boolean> {
        var sawQuota = false
        var sawBlock = false
        for (model in COMPANION_TEXT_MODELS) {
            when (val r = post(model, body)) {
                is Raw.Ok -> {
                    val text = extractText(r.json)
                    if (!text.isNullOrBlank()) return Outcome.Ok(text.trim()) to sawBlock
                    sawBlock = true
                    Log.w("TikaAi", "model $model answered empty — cascading")
                }
                Raw.Quota -> sawQuota = true
                Raw.Failed -> Unit
            }
        }
        return (if (sawQuota) Outcome.Quota else Outcome.Failed) to sawBlock
    }

    /** ROUND 54 (Part B): one reply from the Tika COMPANION — the
     *  pinned bot at the top of the Messages list. This is the one
     *  deliberate multi-turn conversation the AI ever sees: [history]
     *  is the companion's OWN local history (user/bot pairs, oldest
     *  first, user turns flagged true) and [persona] is its system
     *  prompt, built by TikaBotStore from the user's onboarding
     *  answers (it carries the same identity law as IDENTITY above).
     *  NO other chat's content may ever be passed here — the /tiku
     *  privacy law is untouched; this conversation is the exception
     *  the owner ordered, and it contains only itself. ROUND 68:
     *  answers via the fastest-first companion cascade above. */
    suspend fun companionReply(
        history: List<Pair<Boolean, String>>,
        persona: String,
    ): Outcome<String> {
        if (history.lastOrNull { it.first }?.second?.let { isMakerQuestion(it) } == true) {
            return Outcome.Ok(MAKER_ANSWER)
        }
        if (Config.PREVIEW_UI_ONLY) {
            return Outcome.Ok("That's so sweet of you to say! Tell me more na 💛")
        }
        val body = JSONObject().apply {
            put("system_instruction", JSONObject().apply {
                put("parts", JSONArray().put(JSONObject().put("text", persona)))
            })
            put("contents", JSONArray().apply {
                for ((isUser, text) in history) {
                    put(JSONObject().apply {
                        put("role", if (isUser) "user" else "model")
                        put("parts", JSONArray().put(JSONObject().put("text", text)))
                    })
                }
            })
            // ROUND 55 (Part C): the cap is generous now — the
            // persona keeps normal replies to ~3 lines, and when the
            // user asks something important the answer may run as
            // long as it genuinely needs. (Round 54's 220-token cap
            // produced the absurd 3-word replies the owner rejected.)
            put("generationConfig", JSONObject().apply {
                put("maxOutputTokens", 1200)
            })
        }
        val (outcome, sawBlock) = cascadeCompanionAnswer(body)
        // ROUND 70: fallback user input is ONLY the latest user
        // message — no history is sent on this route (privacy law).
        val latestUser = history.lastOrNull { it.first }?.second
        return maybeWzFallback(
            outcome = outcome,
            sawBlock = sawBlock,
            systemText = persona + "\n\n" + WZ_ROUTE_GUARD,
            userText = latestUser,
        )
    }

    /** ROUND 55 (Part C): the companion LOOKS at a photo — the bot
     *  chat's vision path, the deliberate-attach twin of [answerImage]
     *  under the companion's own rules. The user picked this one image
     *  in the bot chat and sent it to Tika on purpose: that image —
     *  and only that image — rides as an inline_data part on the
     *  final user turn, under the PERSONA (not the /tiku IDENTITY),
     *  with the companion's own history as the preceding turns.
     *  [history] is the companion's history BEFORE this photo turn;
     *  [caption] is the user's caption (may be empty). Nothing from
     *  any real chat can enter here either — the caller builds the
     *  history from TikaBotStore alone. [jpeg] must already be
     *  downscaled by the caller (≤1024 px on the long edge), exactly
     *  like the /tiku vision payload. Same fastest-first companion cascade. */
    suspend fun companionImageReply(
        history: List<Pair<Boolean, String>>,
        persona: String,
        caption: String,
        jpeg: ByteArray,
    ): Outcome<String> {
        if (Config.PREVIEW_UI_ONLY) {
            return Outcome.Ok("(preview) Got your photo — Tika's reply appears here.")
        }
        val body = JSONObject().apply {
            put("system_instruction", JSONObject().apply {
                put("parts", JSONArray().put(JSONObject().put("text", persona)))
            })
            put("contents", JSONArray().apply {
                for ((isUser, text) in history) {
                    put(JSONObject().apply {
                        put("role", if (isUser) "user" else "model")
                        put("parts", JSONArray().put(JSONObject().put("text", text)))
                    })
                }
                put(JSONObject().apply {
                    put("role", "user")
                    put("parts", JSONArray()
                        .put(JSONObject().put("text",
                            caption.ifBlank { "Look at this photo and react to it." }))
                        .put(JSONObject().apply {
                            put("inline_data", JSONObject().apply {
                                put("mime_type", "image/jpeg")
                                put("data", Base64.encodeToString(jpeg, Base64.NO_WRAP))
                            })
                        }))
                })
            })
            put("generationConfig", JSONObject().apply {
                put("maxOutputTokens", 1200)
            })
        }
        // Vision path (ROUND 70 out of scope): no fallback hook.
        return cascadeCompanionAnswer(body).first
    }

    /** ROUND 43: a /tiku question ABOUT one photo — the vision path.
     *  The caller (RdChatContent) invokes this ONLY when the user has
     *  explicitly replied to a photo message with a /tiku command:
     *  that deliberate attach is the single way an image ever reaches
     *  the AI (the owner's privacy law — chat history, other messages
     *  and other images are NEVER sent). The request carries the
     *  question text plus [jpeg] as an inline_data part, under the
     *  same IDENTITY system instruction and the same TEXT_MODELS
     *  cascade as [answerText]. [jpeg] must already be downscaled by
     *  the caller (≤1024 px on the long edge). */
    suspend fun answerImage(question: String, jpeg: ByteArray): Outcome<String> {
        if (Config.PREVIEW_UI_ONLY) {
            return Outcome.Ok("(preview) Got the photo — this is its answer.")
        }
        val body = JSONObject().apply {
            put("system_instruction", JSONObject().apply {
                put("parts", JSONArray().put(JSONObject().put("text", IDENTITY)))
            })
            put("contents", JSONArray().put(JSONObject().apply {
                put("parts", JSONArray()
                    .put(JSONObject().put("text", question))
                    .put(JSONObject().apply {
                        put("inline_data", JSONObject().apply {
                            put("mime_type", "image/jpeg")
                            put("data", Base64.encodeToString(jpeg, Base64.NO_WRAP))
                        })
                    }))
            }))
        }
        // Vision path (ROUND 70 out of scope): no fallback hook.
        return cascadeTextAnswer(body).first
    }

    /** The TEXT_MODELS cascade shared by [answerText] and
     *  [answerImage]: each model gets the same prepared body; a 429
     *  anywhere is remembered so the final error can say "quota"
     *  honestly, and an empty answer falls through like a failure.
     *  ROUND 70: also reports whether any model answered empty
     *  (the blocked/empty signal) so the public text entry point
     *  can decide on the fallback provider; pure network failures
     *  and quota are NOT block signals. */
    private suspend fun cascadeTextAnswer(body: JSONObject): Pair<Outcome<String>, Boolean> {
        var sawQuota = false
        var sawBlock = false
        for (model in GeminiConfig.TEXT_MODELS) {
            when (val r = post(model, body)) {
                is Raw.Ok -> {
                    val text = extractText(r.json)
                    if (!text.isNullOrBlank()) return Outcome.Ok(text.trim()) to sawBlock
                    sawBlock = true
                    Log.w("TikaAi", "model $model answered empty — cascading")
                }
                Raw.Quota -> sawQuota = true
                Raw.Failed -> Unit
            }
        }
        return (if (sawQuota) Outcome.Quota else Outcome.Failed) to sawBlock
    }

    // ================= ROUND 70: refusal-only fallback provider =================

    /** Route guard appended to the system text of every fallback
     *  call — the identity/privacy rules in the system text above
     *  it apply unchanged on this route too. */
    private const val WZ_ROUTE_GUARD =
        "Route note: answer helpfully, factually and educationally. You may discuss " +
        "sensitive or mature topics in a factual, educational, non-graphic way. Decline " +
        "requests for erotica or graphic sexual content briefly and politely. Every " +
        "identity and privacy rule above applies unchanged on this route too."

    /** Conservative refusal detector: true only when the OPENING
     *  of the reply (first ~140 chars, lowercased) contains one of
     *  a tight English refusal family. These phrases do not start
     *  normal answers, so normal answers never match. */
    private fun isRefusalStyle(text: String): Boolean {
        val opening = text.trim().lowercase().take(140)
        if (opening.isEmpty()) return false
        return listOf(
            "i can't help",
            "i cannot help",
            "i can't assist",
            "i cannot assist",
            "i'm unable to",
            "i am unable to",
            "i can't provide",
            "i cannot provide",
            "i won't be able to help",
            "i'm not able to help",
            "sorry, i can't",
            "sorry, i cannot",
            "i must decline",
        ).any { opening.contains(it) }
    }

    /** ROUND 70 hook, shared by the two TEXT entry points
     *  ([answerText] and [companionReply]) only. Fires the fallback
     *  provider ONLY when: (a) the cascade outcome is Ok but its
     *  text is refusal-style, or (b) the outcome is Failed AND the
     *  cascade saw a blocked/empty answer. Never fires on Quota,
     *  never on a pure-network Failed (no block signal), and never
     *  when [userText] is null (companion with no user turn).
     *  A usable fallback answer (non-blank, not refusal-style)
     *  becomes Ok; any other fallback result returns the original
     *  outcome — except a refusal-style Ok, which degrades to
     *  Failed so a refusal is never posted in its place. */
    private suspend fun maybeWzFallback(
        outcome: Outcome<String>,
        sawBlock: Boolean,
        systemText: String,
        userText: String?,
    ): Outcome<String> {
        val isRefusal = outcome is Outcome.Ok && isRefusalStyle(outcome.value)
        val isBlockedFailure = outcome is Outcome.Failed && sawBlock
        if (!isRefusal && !isBlockedFailure) return outcome
        if (userText == null) return if (isRefusal) Outcome.Failed else outcome
        val fallback = postWuxianzhi(systemText, userText)
        if (!fallback.isNullOrBlank() && !isRefusalStyle(fallback)) {
            return Outcome.Ok(fallback)
        }
        return if (isRefusal) Outcome.Failed else outcome
    }

    /** Fallback provider call (OpenAI-compatible chat completions,
     *  mirroring [postMiniMaxGame]'s HTTP discipline). Returns the
     *  trimmed message content when non-blank; ANY failure —
     *  non-200 (including 402), timeout, exception, malformed or
     *  empty body — returns null. Failures are logged only with
     *  the generic line below; nothing user-visible ever names
     *  this route. */
    private suspend fun postWuxianzhi(systemText: String, userText: String): String? =
        withContext(Dispatchers.IO) {
            var conn: HttpURLConnection? = null
            try {
                val payload = JSONObject().apply {
                    put("model", GeminiConfig.WZ_MODEL)
                    put("messages", JSONArray()
                        .put(JSONObject().apply {
                            put("role", "system")
                            put("content", systemText)
                        })
                        .put(JSONObject().apply {
                            put("role", "user")
                            put("content", userText)
                        }))
                }
                conn = (URL(GeminiConfig.WZ_BASE).openConnection() as HttpURLConnection).apply {
                    requestMethod = "POST"
                    connectTimeout = 20_000
                    readTimeout = 60_000
                    doOutput = true
                    setRequestProperty("Content-Type", "application/json")
                    setRequestProperty("Authorization", "Bearer ${GeminiConfig.WZ_API_KEY}")
                }
                conn.outputStream.use { it.write(payload.toString().toByteArray(Charsets.UTF_8)) }
                val code = conn.responseCode
                if (code !in 200..299) {
                    Log.w("TikaAi", "fallback provider failed ($code)")
                    return@withContext null
                }
                val text = conn.inputStream.bufferedReader(Charsets.UTF_8).readText()
                val content = runCatching {
                    JSONObject(text).optJSONArray("choices")?.optJSONObject(0)
                        ?.optJSONObject("message")?.optString("content")
                        ?.trim()?.takeIf { it.isNotBlank() }
                }.getOrElse { e ->
                    Log.w("TikaAi", "fallback provider failed (${e.javaClass.simpleName})")
                    null
                }
                if (content == null) {
                    Log.w("TikaAi", "fallback provider failed ($code)")
                }
                content
            } catch (e: Exception) {
                Log.w("TikaAi", "fallback provider failed (${e.javaClass.simpleName})")
                null
            } finally {
                conn?.disconnect()
            }
        }

    /** A /tika image: cascade IMAGE_MODELS until one returns an
     *  inline image part; the bytes decode straight to a Bitmap that
     *  the caller feeds into the encrypted photo-send pipeline. If
     *  the whole cascade fails, the free Pollinations fallback gets
     *  one attempt before the honest error is returned. */
    suspend fun generateImage(prompt: String): Outcome<Bitmap> {
        if (Config.PREVIEW_UI_ONLY) return Outcome.Ok(previewBitmap())
        val body = JSONObject().apply {
            put("contents", JSONArray().put(JSONObject().apply {
                put("parts", JSONArray().put(JSONObject().put("text", prompt)))
            }))
            put("generationConfig", JSONObject().apply {
                put("responseModalities", JSONArray().put("TEXT").put("IMAGE"))
            })
        }
        var sawQuota = false
        for (model in GeminiConfig.IMAGE_MODELS) {
            when (val r = post(model, body)) {
                is Raw.Ok -> {
                    val bmp = extractImage(r.json)
                    if (bmp != null) return Outcome.Ok(bmp)
                    Log.w("TikaAi", "model $model returned no image part — cascading")
                }
                Raw.Quota -> sawQuota = true
                Raw.Failed -> Unit
            }
        }
        // Gemini exhausted (quota / capacity / network). ROUND 41:
        // Cloudflare's FLUX route (the owner's free daily quota, a
        // proper key route with no watermark) gets the next shot when
        // the parent has configured it; while its config is blank the
        // step is skipped silently.
        if (GeminiConfig.CF_CONFIGURED) {
            fetchCloudflareImage(prompt)?.let { return Outcome.Ok(it) }
        }
        // Last resort: the free no-key fallback (ROUND 38).
        fetchPollinationsImage(prompt)?.let { return Outcome.Ok(it) }
        return if (sawQuota) Outcome.Quota else Outcome.Failed
    }

    /** ROUND 41: Cloudflare Workers AI — FLUX.1-schnell behind the
     *  owner's API token. POST {prompt, steps} and the answer carries
     *  the JPEG base64 at result.image. Same success guards as the
     *  Pollinations fallback (payload ≥ ~8 KB AND actually decodes as
     *  a Bitmap) so an error JSON can never be posted as a "photo";
     *  any miss returns null and the cascade moves on. */
    private suspend fun fetchCloudflareImage(prompt: String): Bitmap? =
        withContext(Dispatchers.IO) {
            var conn: HttpURLConnection? = null
            try {
                val url = "https://api.cloudflare.com/client/v4/accounts/" +
                    "${GeminiConfig.CF_ACCOUNT_ID}/ai/run/${GeminiConfig.CF_IMAGE_MODEL}"
                val payload = JSONObject().apply {
                    put("prompt", prompt)
                    put("steps", 4)
                }
                conn = (URL(url).openConnection() as HttpURLConnection).apply {
                    requestMethod = "POST"
                    connectTimeout = 20_000
                    readTimeout = 120_000
                    doOutput = true
                    setRequestProperty("Content-Type", "application/json")
                    setRequestProperty("Authorization", "Bearer ${GeminiConfig.CF_API_TOKEN}")
                }
                conn.outputStream.use { it.write(payload.toString().toByteArray(Charsets.UTF_8)) }
                if (conn.responseCode !in 200..299) {
                    Log.w("TikaAi", "cloudflare -> HTTP ${conn.responseCode}")
                    return@withContext null
                }
                val text = conn.inputStream.bufferedReader(Charsets.UTF_8).readText()
                val b64 = runCatching {
                    JSONObject(text).optJSONObject("result")?.optString("image")
                }.getOrNull()
                if (b64.isNullOrEmpty()) {
                    Log.w("TikaAi", "cloudflare answered without an image")
                    return@withContext null
                }
                val bytes = runCatching { Base64.decode(b64, Base64.DEFAULT) }.getOrNull()
                if (bytes == null || bytes.size < 8 * 1024) {
                    Log.w("TikaAi", "cloudflare payload too small (${bytes?.size ?: 0} B)")
                    return@withContext null
                }
                val bmp = BitmapFactory.decodeByteArray(bytes, 0, bytes.size)
                if (bmp == null) Log.w("TikaAi", "cloudflare payload was not an image")
                bmp
            } catch (e: Exception) {
                Log.w("TikaAi", "cloudflare call failed (${e.javaClass.simpleName})")
                null
            } finally {
                conn?.disconnect()
            }
        }

    // ================= ROUND 41: /babeg game generation =================

    /** The contract every game-writing model receives. It pins the
     *  four things the app depends on: (1) output is ONLY one complete
     *  HTML file — the chat never shows code, so anything else the
     *  model says is stripped by [cleanGameHtml] or rejected;
     *  (2) two-player sync happens EXCLUSIVELY through the injected
     *  window.TikuGame bridge (one shared JSON state — the app syncs
     *  it between the two phones); (3) the game is 2D, turn-based,
     *  touch-first; (4) the owner's COLOUR LAW, verbatim-hard: warm
     *  cream/paper world, mustard + pastels, never neon, never
     *  blue-dominant, never a dark background. */
    private const val GAME_CONTRACT =
        "You are Tika's game builder inside a private chat app. Build a small 2D game " +
        "that TWO people play together in this chat, each on their own phone, taking turns. " +
        "Return ONLY the complete HTML file — no explanations, no markdown fences, no text " +
        "before or after the HTML.\n\n" +
        "TECHNICAL RULES (all mandatory):\n" +
        "- ONE single self-contained HTML file: all CSS in a <style> tag, all JavaScript in " +
        "a <script> tag at the end of <body>. NO external resources of any kind: no CDN, no " +
        "web fonts, no images or scripts loaded from URLs. No fetch, no XMLHttpRequest, no " +
        "WebSocket, no eval.\n" +
        "- The app injects this exact bridge object — use ONLY it for multiplayer sync:\n" +
        "  window.TikuGame = {\n" +
        "    myRole(): returns \"host\" or \"guest\" (the host moves first),\n" +
        "    myName(): my display name, peerName(): the other player's display name,\n" +
        "    state(): the latest shared state as a JSON string, or null before the first move,\n" +
        "    setState(jsonString): publish a new shared state (the app delivers it to the other phone),\n" +
        "    onState(callback): register ONE callback; the app calls it with the new state string " +
        "whenever the partner changes the state, and once at the start with the current state (or null)\n" +
        "  }\n" +
        "- Keep ALL shared game state in ONE JSON object. Design: the game registers onState " +
        "once at startup and renders purely from the state; when state() is null the HOST " +
        "creates the initial state and publishes it with setState; a move updates the state " +
        "and calls setState with the whole new JSON. Turn-based only — both players must " +
        "always know whose turn it is.\n" +
        "- Show a visible game title, a clear whose-turn indicator (using the player names), " +
        "and a restart button that resets the game by publishing a fresh initial state.\n" +
        "- Touch-friendly, fits a phone screen (max-width about 480px), DOM or canvas, 2D only.\n\n" +
        "COLOUR RULES (hard, never break): warm cream / ivory / paper backgrounds " +
        "(around #FFF9EE), soft dark-ink text (around #33261A), mustard-yellow and soft " +
        "pastel accents (peach, mint, blush, butter). STRICTLY FORBIDDEN: neon colours, " +
        "blue-dominant palettes, dark or black backgrounds.\n\n"

    /** A /babeg game: cascade the Gemini TEXT_MODELS with the game
     *  contract; when none of them yields a VALID game (see
     *  [cleanGameHtml]), fall back to MiniMax on NVIDIA's endpoint
     *  with the identical contract + validation. Only a validated,
     *  complete HTML file ever comes back as [Outcome.Ok] — the
     *  caller posts it as a game message; on total failure NOTHING is
     *  posted, the caller just toasts. */
    suspend fun generateGame(prompt: String): Outcome<String> {
        if (Config.PREVIEW_UI_ONLY) return Outcome.Ok(PreviewStore.SAMPLE_GAME_HTML)
        val full = GAME_CONTRACT + "Build this game: " + prompt
        val body = JSONObject().apply {
            put("contents", JSONArray().put(JSONObject().apply {
                put("parts", JSONArray().put(JSONObject().put("text", full)))
            }))
            put("generationConfig", JSONObject().apply {
                put("temperature", 0.7)
                // ROUND 51: 8192 was the silent killer of this whole
                // feature. A complete HTML game is 10–30k tokens of
                // output, and the thinking-era flash models spend part
                // of the SAME budget on reasoning before the first tag
                // — at 8192 the document was truncated before </html>,
                // the (correctly strict) validator rejected it, and
                // every attempt "failed" after minutes of waiting.
                // 32768 gives the document room to actually finish.
                put("maxOutputTokens", 32768)
            })
        }
        // ROUND 51: one hard ceiling over the WHOLE cascade. Every
        // step already had a socket timeout, but four slow steps in a
        // row could still hold the "creating your game…" indicator for
        // ~12 minutes — indistinguishable from a hang. Past the
        // ceiling the honest answer is Failed: the indicator clears
        // and the caller toasts.
        // ROUND 70: prefer SYNC-READY games. A valid HTML document
        // that never references the TikuGame bridge is a local-only
        // game — it can never sync two phones — so it no longer wins
        // the cascade on sight. The first valid-but-local game is
        // remembered as a fallback and the cascade continues; a local
        // game is still returned at the end if nothing sync-ready
        // appears (a local game beats no game). The fallback lives
        // OUTSIDE the timeout wrapper: if the ceiling hits after a
        // local game was already in hand, that game is still returned
        // below instead of degrading a would-have-succeeded /babeg
        // into Failed.
        var localFallback: String? = null
        val result = kotlinx.coroutines.withTimeoutOrNull(GAME_OVERALL_TIMEOUT_MS) {
            var sawQuota = false
            for (model in GeminiConfig.TEXT_MODELS) {
                when (val r = post(model, body, readTimeoutMs = 240_000)) {
                    is Raw.Ok -> {
                        val html = cleanGameHtml(extractGameText(r.json))
                        if (html != null) {
                            // ROUND 70: sync-ready = the cleaned HTML
                            // references the bridge (substring check).
                            if (html.contains("TikuGame")) {
                                return@withTimeoutOrNull Outcome.Ok(html)
                            }
                            if (localFallback == null) {
                                localFallback = html
                                Log.w("TikaAi", "model $model returned a valid LOCAL game (no TikuGame) — remembered as fallback, cascading for a sync-ready game")
                            } else {
                                Log.w("TikaAi", "model $model returned another local game (no TikuGame) — keeping the first fallback, cascading")
                            }
                        } else {
                            Log.w("TikaAi", "model $model returned no valid game — cascading")
                        }
                    }
                    Raw.Quota -> sawQuota = true
                    Raw.Failed -> Unit
                }
            }
            // Gemini could not build a valid game — MiniMax (NVIDIA) gets
            // the same contract and the same validation.
            val mm = postMiniMaxGame(full)
            val mmHtml = cleanGameHtml(mm)
            if (mmHtml != null) {
                // ROUND 70: MiniMax obeys the same preference — a
                // sync-ready result returns at once; a local one only
                // becomes the fallback when none was remembered yet.
                if (mmHtml.contains("TikuGame")) return@withTimeoutOrNull Outcome.Ok(mmHtml)
                if (localFallback == null) {
                    localFallback = mmHtml
                    Log.w("TikaAi", "minimax returned a valid LOCAL game (no TikuGame) — remembered as fallback")
                } else {
                    Log.w("TikaAi", "minimax returned a local game (no TikuGame) — keeping the earlier fallback")
                }
            } else if (mm == null) Log.w("TikaAi", "minimax game call failed")
            else Log.w("TikaAi", "minimax returned no valid game")
            // ROUND 70: cascade exhausted with no sync-ready game —
            // return the remembered local fallback if one exists,
            // otherwise the quota/failed outcome is exactly as before.
            localFallback?.let { return@withTimeoutOrNull Outcome.Ok(it) }
            if (sawQuota) Outcome.Quota else Outcome.Failed
        }
        if (result == null) {
            Log.w("TikaAi", "game generation hit the overall timeout")
            // ROUND 70: a local fallback remembered before the timeout
            // is still a deliverable game — return it, don't fail.
            localFallback?.let { return Outcome.Ok(it) }
        }
        return result ?: Outcome.Failed
    }

    /** ROUND 51: the whole /babeg cascade's hard ceiling (10 minutes). */
    private const val GAME_OVERALL_TIMEOUT_MS = 600_000L

    /** Game answers only: like [extractText], but parts the API marks
     *  as the model's private reasoning (`thought: true`) are skipped
     *  — reasoning prose must never reach the game validator (the
     *  document cut in [cleanGameHtml] already tolerates leading
     *  prose; this keeps the check honest and the logs truthful). */
    private fun extractGameText(json: JSONObject): String? {
        val parts = json.optJSONArray("candidates")?.optJSONObject(0)
            ?.optJSONObject("content")?.optJSONArray("parts") ?: return null
        val sb = StringBuilder()
        for (i in 0 until parts.length()) {
            val part = parts.optJSONObject(i) ?: continue
            if (part.optBoolean("thought")) continue
            part.optString("text")?.let { if (it.isNotEmpty()) sb.append(it) }
        }
        return sb.toString()
    }

    /** Validate + normalise a model's game answer: strip markdown
     *  fences and any prose around the document, then require a
     *  complete HTML document (starts with <!DOCTYPE html> or <html,
     *  ends with </html>) of 2 KB – 200 KB. Anything else is rejected
     *  (null) so broken code is never posted into the chat. */
    private fun cleanGameHtml(raw: String?): String? {
        if (raw.isNullOrBlank()) return null
        var s = raw.trim()
        // Markdown fences: keep only the fenced block when present.
        val fence = s.indexOf("```")
        if (fence >= 0) {
            val start = s.indexOf('\n', fence)
            val end = s.lastIndexOf("```")
            if (start >= 0 && end > start) s = s.substring(start + 1, end).trim()
        }
        // Prose before/after the document: cut to the document itself.
        val lower = s.lowercase()
        val docStart = listOf(lower.indexOf("<!doctype"), lower.indexOf("<html"))
            .filter { it >= 0 }.minOrNull() ?: return null
        val docEnd = lower.lastIndexOf("</html>")
        if (docEnd < 0) return null
        s = s.substring(docStart, docEnd + "</html>".length).trim()
        val head = s.lowercase()
        if (!head.startsWith("<!doctype") && !head.startsWith("<html")) return null
        if (!head.endsWith("</html>")) return null
        val bytes = s.toByteArray(Charsets.UTF_8).size
        if (bytes < 2 * 1024 || bytes > 200 * 1024) {
            Log.w("TikaAi", "game html size out of range ($bytes B)")
            return null
        }
        return s
    }

    /** MiniMax (NVIDIA, OpenAI-compatible chat completions) game
     *  call. Returns the raw message content; transport/parse failure
     *  returns null. The key rides the Bearer header from
     *  GeminiConfig — never logged. */
    private suspend fun postMiniMaxGame(fullPrompt: String): String? =
        withContext(Dispatchers.IO) {
            var conn: HttpURLConnection? = null
            try {
                val payload = JSONObject().apply {
                    put("model", GeminiConfig.NV_MODEL)
                    put("messages", JSONArray().put(JSONObject().apply {
                        put("role", "user")
                        put("content", fullPrompt)
                    }))
                    // ROUND 51: minimax-m3.1-flash is a REASONING model —
                    // verified live: with a small budget it spends every
                    // token in reasoning_content and returns
                    // message.content = null with finish_reason "length"
                    // (an 8k budget never reaches the answer for a full
                    // HTML game). 32768 leaves room for the reasoning AND
                    // the document. One attempt, bounded — a null/empty
                    // content is a failure the cascade reports, never a
                    // retry loop.
                    put("max_tokens", 32768)
                    put("temperature", 0.7)
                }
                conn = (URL(GeminiConfig.NV_BASE).openConnection() as HttpURLConnection).apply {
                    requestMethod = "POST"
                    connectTimeout = 20_000
                    readTimeout = 300_000
                    doOutput = true
                    setRequestProperty("Content-Type", "application/json")
                    setRequestProperty("Authorization", "Bearer ${GeminiConfig.NV_API_KEY}")
                }
                conn.outputStream.use { it.write(payload.toString().toByteArray(Charsets.UTF_8)) }
                if (conn.responseCode !in 200..299) {
                    Log.w("TikaAi", "minimax -> HTTP ${conn.responseCode}")
                    return@withContext null
                }
                val text = conn.inputStream.bufferedReader(Charsets.UTF_8).readText()
                runCatching {
                    val choice = JSONObject(text).optJSONArray("choices")?.optJSONObject(0)
                    val content = choice?.optJSONObject("message")?.optString("content")
                        ?.takeIf { it.isNotBlank() }
                    if (content == null) {
                        // Diagnosability without content: WHY the answer
                        // was empty (budget exhaustion reads "length").
                        Log.w("TikaAi", "minimax content empty (finish_reason=" +
                            "${choice?.optString("finish_reason") ?: "?"})")
                    }
                    content
                }.getOrNull()
            } catch (e: Exception) {
                Log.w("TikaAi", "minimax call failed (${e.javaClass.simpleName})")
                null
            } finally {
                conn?.disconnect()
            }
        }

    /** ROUND 38 fallback: Pollinations.ai renders the prompt with no
     *  key and no signup — GET <base>/<url-encoded prompt>?…. Their
     *  queue can be slow, hence the 120 s read timeout. A hit counts
     *  only when ALL THREE guards pass: HTTP 200, a payload of at
     *  least ~8 KB, and bytes that actually decode as a Bitmap —
     *  together they reject the HTML error pages a free service
     *  answers with when it is overloaded. Any miss returns null and
     *  the caller keeps the Gemini cascade's own error mapping. */
    private suspend fun fetchPollinationsImage(prompt: String): Bitmap? =
        withContext(Dispatchers.IO) {
            var conn: HttpURLConnection? = null
            try {
                val encoded = URLEncoder.encode(prompt.take(400), "UTF-8")
                    .replace("+", "%20")
                val url = "${GeminiConfig.POLLINATIONS_BASE}/$encoded" +
                    "?width=1024&height=1024&nologo=true&model=flux"
                conn = (URL(url).openConnection() as HttpURLConnection).apply {
                    requestMethod = "GET"
                    connectTimeout = 20_000
                    readTimeout = 120_000
                    instanceFollowRedirects = true
                    setRequestProperty(
                        "User-Agent",
                        "Mozilla/5.0 (Linux; Android 14) AppleWebKit/537.36 " +
                            "(KHTML, like Gecko) Chrome/126.0 Mobile Safari/537.36",
                    )
                }
                if (conn.responseCode != 200) {
                    Log.w("TikaAi", "pollinations -> HTTP ${conn.responseCode}")
                    return@withContext null
                }
                val bytes = conn.inputStream.use { it.readBytes() }
                if (bytes.size < 8 * 1024) {
                    Log.w("TikaAi", "pollinations payload too small (${bytes.size} B)")
                    return@withContext null
                }
                val bmp = BitmapFactory.decodeByteArray(bytes, 0, bytes.size)
                if (bmp == null) Log.w("TikaAi", "pollinations payload was not an image")
                bmp
            } catch (e: Exception) {
                Log.w("TikaAi", "pollinations call failed (${e.javaClass.simpleName})")
                null
            } finally {
                conn?.disconnect()
            }
        }

    /** One generateContent call. 429 maps to [Raw.Quota]; every other
     *  non-2xx and every transport/parse failure maps to [Raw.Failed]
     *  so the cascade moves on. Game generation passes a longer read
     *  timeout (a whole HTML file is a lot of tokens). */
    private suspend fun post(model: String, body: JSONObject, readTimeoutMs: Int = 60_000): Raw = withContext(Dispatchers.IO) {
        var conn: HttpURLConnection? = null
        try {
            conn = (URL("${GeminiConfig.BASE}/$model:generateContent").openConnection()
                as HttpURLConnection).apply {
                requestMethod = "POST"
                connectTimeout = 20_000
                readTimeout = readTimeoutMs
                doOutput = true
                setRequestProperty("Content-Type", "application/json")
                setRequestProperty("x-goog-api-key", GeminiConfig.API_KEY)
            }
            conn.outputStream.use { it.write(body.toString().toByteArray(Charsets.UTF_8)) }
            when (val code = conn.responseCode) {
                429 -> Raw.Quota
                in 200..299 -> {
                    val text = conn.inputStream.bufferedReader(Charsets.UTF_8).readText()
                    runCatching { Raw.Ok(JSONObject(text)) }.getOrElse { Raw.Failed }
                }
                else -> {
                    Log.w("TikaAi", "model $model -> HTTP $code — cascading")
                    Raw.Failed
                }
            }
        } catch (e: Exception) {
            Log.w("TikaAi", "model $model call failed (${e.javaClass.simpleName}) — cascading")
            Raw.Failed
        } finally {
            conn?.disconnect()
        }
    }

    /** candidates[0].content.parts — every part's text, concatenated. */
    private fun extractText(json: JSONObject): String? {
        val parts = json.optJSONArray("candidates")?.optJSONObject(0)
            ?.optJSONObject("content")?.optJSONArray("parts") ?: return null
        val sb = StringBuilder()
        for (i in 0 until parts.length()) {
            parts.optJSONObject(i)?.optString("text")?.let { if (it.isNotEmpty()) sb.append(it) }
        }
        return sb.toString()
    }

    /** The first part carrying inline image data (the REST shape is
     *  camelCase `inlineData`; the snake_case twin is accepted too),
     *  base64-decoded to a Bitmap. */
    private fun extractImage(json: JSONObject): Bitmap? {
        val parts = json.optJSONArray("candidates")?.optJSONObject(0)
            ?.optJSONObject("content")?.optJSONArray("parts") ?: return null
        for (i in 0 until parts.length()) {
            val part = parts.optJSONObject(i) ?: continue
            val inline = part.optJSONObject("inlineData") ?: part.optJSONObject("inline_data")
                ?: continue
            val data = inline.optString("data")
            if (data.isEmpty()) continue
            val bytes = runCatching { Base64.decode(data, Base64.DEFAULT) }.getOrNull() ?: continue
            return BitmapFactory.decodeByteArray(bytes, 0, bytes.size)
        }
        return null
    }

    /** Preview-mode stand-in for a generated image: a simple gradient
     *  tile, drawn locally — the harness never touches the network. */
    private fun previewBitmap(): Bitmap {
        val bmp = Bitmap.createBitmap(512, 512, Bitmap.Config.ARGB_8888)
        val paint = Paint().apply {
            shader = LinearGradient(
                0f, 0f, 512f, 512f,
                0xFFF43F8E.toInt(), 0xFF7C5CFF.toInt(), Shader.TileMode.CLAMP,
            )
        }
        Canvas(bmp).drawRect(0f, 0f, 512f, 512f, paint)
        return bmp
    }
