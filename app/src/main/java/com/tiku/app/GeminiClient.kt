package com.tiku.app

import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.graphics.Canvas
import android.graphics.LinearGradient
import android.graphics.Paint
import android.graphics.Shader
import android.util.Base64
import android.util.Log
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.json.JSONArray
import org.json.JSONObject
import java.net.HttpURLConnection
import java.net.URL

/**
 * ROUND 37 — TIKA, the in-chat AI (owner's order, Meta-AI style).
 *
 * The chat composer understands two commands (see RdChatContent):
 *   /tiku <question>  -> a TEXT answer from Gemini
 *   /tika <prompt>    -> an IMAGE generated by Gemini
 * The asking client makes the call and then posts the result into the
 * thread as a normal encrypted message carrying the additive `ai`
 * flag (TikuMessage.ai) — both phones render it as Tika's bubble.
 *
 * Transport is deliberately dependency-free: HttpURLConnection +
 * org.json (both already used across this codebase), the key riding
 * the `x-goog-api-key` header from GeminiConfig. Every model in the
 * config's cascade is tried in order — a 429 / 503 / 404 / empty
 * answer falls through to the next model, so one model's quota or a
 * renamed model never silences Tika while another still answers.
 * Outcomes are honest: [Outcome.Quota] only when the cascade saw a
 * 429 and nothing succeeded, [Outcome.Failed] for everything else —
 * the caller toasts and posts NOTHING fake.
 *
 * Timeouts are generous (image generation is slow): 20 s connect,
 * 60 s read, per model, on Dispatchers.IO.
 */
object GeminiClient {

    sealed interface Outcome<out T> {
        data class Ok<T>(val value: T) : Outcome<T>
        data object Quota : Outcome<Nothing>
        data object Failed : Outcome<Nothing>
    }

    private sealed interface Raw {
        data class Ok(val json: JSONObject) : Raw
        data object Quota : Raw
        data object Failed : Raw
    }

    /** Who Tika is, prepended to text asks only (image prompts go to
     *  the image models verbatim — a persona line would pollute the
     *  picture). */
    private const val PERSONA =
        "You are Tika, a friendly AI assistant inside a private chat app. " +
        "Answer briefly and helpfully, in the same language the user wrote in."

    /** A /tiku text answer: cascade TEXT_MODELS until one returns a
     *  non-empty answer. */
    suspend fun answerText(prompt: String): Outcome<String> {
        if (Config.PREVIEW_UI_ONLY) {
            return Outcome.Ok(
                "Preview mode — asli app me Tika yahin Gemini ka jawab dikhayega. Tumne pucha tha: $prompt",
            )
        }
        val body = JSONObject().apply {
            put("contents", JSONArray().put(JSONObject().apply {
                put("parts", JSONArray().put(JSONObject().put("text", "$PERSONA\n\n$prompt")))
            }))
        }
        var sawQuota = false
        for (model in GeminiConfig.TEXT_MODELS) {
            when (val r = post(model, body)) {
                is Raw.Ok -> {
                    val text = extractText(r.json)
                    if (!text.isNullOrBlank()) return Outcome.Ok(text.trim())
                    Log.w("TikaAi", "model $model answered empty — cascading")
                }
                Raw.Quota -> sawQuota = true
                Raw.Failed -> Unit
            }
        }
        return if (sawQuota) Outcome.Quota else Outcome.Failed
    }

    /** A /tika image: cascade IMAGE_MODELS until one returns an
     *  inline image part; the bytes decode straight to a Bitmap that
     *  the caller feeds into the encrypted photo-send pipeline. */
    suspend fun generateImage(prompt: String): Outcome<Bitmap> {
        if (Config.PREVIEW_UI_ONLY) return Outcome.Ok(previewBitmap())
        val body = JSONObject().apply {
            put("contents", JSONArray().put(JSONObject().apply {
                put("parts", JSONArray().put(JSONObject().put("text", prompt)))
            }))
            put("generationConfig", JSONObject().apply {
                put("responseModalities", JSONArray().put("TEXT").put("IMAGE"))
            })
        }
        var sawQuota = false
        for (model in GeminiConfig.IMAGE_MODELS) {
            when (val r = post(model, body)) {
                is Raw.Ok -> {
                    val bmp = extractImage(r.json)
                    if (bmp != null) return Outcome.Ok(bmp)
                    Log.w("TikaAi", "model $model returned no image part — cascading")
                }
                Raw.Quota -> sawQuota = true
                Raw.Failed -> Unit
            }
        }
        return if (sawQuota) Outcome.Quota else Outcome.Failed
    }

    /** One generateContent call. 429 maps to [Raw.Quota]; every other
     *  non-2xx and every transport/parse failure maps to [Raw.Failed]
     *  so the cascade moves on. */
    private suspend fun post(model: String, body: JSONObject): Raw = withContext(Dispatchers.IO) {
        var conn: HttpURLConnection? = null
        try {
            conn = (URL("${GeminiConfig.BASE}/$model:generateContent").openConnection()
                as HttpURLConnection).apply {
                requestMethod = "POST"
                connectTimeout = 20_000
                readTimeout = 60_000
                doOutput = true
                setRequestProperty("Content-Type", "application/json")
                setRequestProperty("x-goog-api-key", GeminiConfig.API_KEY)
            }
            conn.outputStream.use { it.write(body.toString().toByteArray(Charsets.UTF_8)) }
            when (val code = conn.responseCode) {
                429 -> Raw.Quota
                in 200..299 -> {
                    val text = conn.inputStream.bufferedReader(Charsets.UTF_8).readText()
                    runCatching { Raw.Ok(JSONObject(text)) }.getOrElse { Raw.Failed }
                }
                else -> {
                    Log.w("TikaAi", "model $model -> HTTP $code — cascading")
                    Raw.Failed
                }
            }
        } catch (e: Exception) {
            Log.w("TikaAi", "model $model call failed (${e.javaClass.simpleName}) — cascading")
            Raw.Failed
        } finally {
            conn?.disconnect()
        }
    }

    /** candidates[0].content.parts — every part's text, concatenated. */
    private fun extractText(json: JSONObject): String? {
        val parts = json.optJSONArray("candidates")?.optJSONObject(0)
            ?.optJSONObject("content")?.optJSONArray("parts") ?: return null
        val sb = StringBuilder()
        for (i in 0 until parts.length()) {
            parts.optJSONObject(i)?.optString("text")?.let { if (it.isNotEmpty()) sb.append(it) }
        }
        return sb.toString()
    }

    /** The first part carrying inline image data (the REST shape is
     *  camelCase `inlineData`; the snake_case twin is accepted too),
     *  base64-decoded to a Bitmap. */
    private fun extractImage(json: JSONObject): Bitmap? {
        val parts = json.optJSONArray("candidates")?.optJSONObject(0)
            ?.optJSONObject("content")?.optJSONArray("parts") ?: return null
        for (i in 0 until parts.length()) {
            val part = parts.optJSONObject(i) ?: continue
            val inline = part.optJSONObject("inlineData") ?: part.optJSONObject("inline_data")
                ?: continue
            val data = inline.optString("data")
            if (data.isEmpty()) continue
            val bytes = runCatching { Base64.decode(data, Base64.DEFAULT) }.getOrNull() ?: continue
            return BitmapFactory.decodeByteArray(bytes, 0, bytes.size)
        }
        return null
    }

    /** Preview-mode stand-in for a generated image: a simple gradient
     *  tile, drawn locally — the harness never touches the network. */
    private fun previewBitmap(): Bitmap {
        val bmp = Bitmap.createBitmap(512, 512, Bitmap.Config.ARGB_8888)
        val paint = Paint().apply {
            shader = LinearGradient(
                0f, 0f, 512f, 512f,
                0xFFF43F8E.toInt(), 0xFF7C5CFF.toInt(), Shader.TileMode.CLAMP,
            )
        }
        Canvas(bmp).drawRect(0f, 0f, 512f, 512f, paint)
        return bmp
    }
}
